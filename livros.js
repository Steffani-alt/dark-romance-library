const parametros = new URLSearchParams(window.location.search);
const identificador = parametros.get("livro");
const livro = livros[identificador];

const titulo = document.getElementById("livro-titulo");
const capa = document.getElementById("livro-capa");

if (!livro) {
    document.querySelector(".detalhes-livro").innerHTML = `
        <div class="livro-nao-encontrado">
            <h1>Livro não encontrado</h1>
            <p>Esta história ainda não está disponível em nossa biblioteca.</p>
            <a href="index.html">Voltar à biblioteca</a>
        </div>
    `;
} else {
    localStorage.setItem("noirLivroAtual", JSON.stringify(livro));

    document.title = `${livro.titulo} | NOIR LIBRARY`;
    
    titulo.textContent = livro.titulo;
    document.getElementById("capa-titulo").textContent = livro.titulo;
    document.getElementById("livro-autor").textContent = livro.autor;
    document.getElementById("livro-genero").textContent = livro.genero;
    document.getElementById("livro-classificacao").textContent = livro.classificacao;
    document.getElementById("livro-frase").textContent = `“${livro.frase}”`;
    document.getElementById("livro-sinopse").textContent = livro.sinopse;
    document.getElementById("livro-personagens").textContent = livro.personagens;
    document.getElementById("livro-avisos").textContent = livro.avisos;


    capa.style.background = livro.cor;

    const lista = document.getElementById("lista-capitulos");

    
livro.capitulos.forEach((capitulo, indice) => {
    const item = document.createElement("details");
    item.className = "capitulo-item";

    const numero = String(indice + 1).padStart(2, "0");

   
item.innerHTML = `
    <a class="link-capitulo"
       href="leitura.html?livro=${identificador}&capitulo=${indice}">
        <span class="numero-capitulo">${numero}</span>
        <span class="titulo-capitulo">${capitulo.titulo}</span>
        <span class="abrir-capitulo">→</span>
    </a>
`;

lista.appendChild(item);

    const botaoLer = item.querySelector(".botao-abrir-leitura");

    botaoLer.addEventListener("click", () => {
        localStorage.setItem("noirLivroAtual", JSON.stringify(livro));
        localStorage.setItem("noirLivroId", identificador);
        localStorage.setItem("noirCapituloAtual", indice);

        window.location.href = "leitura.html";
    });

    lista.appendChild(item);
});



    // Sistema de favoritos
    const botaoFavorito = document.getElementById("botao-favorito");
    let favoritos = JSON.parse(localStorage.getItem("noirFavorites")) || [];

    function atualizarBotao() {
        const salvo = favoritos.includes(identificador);
        botaoFavorito.textContent = salvo
            ? "♥ Remover dos favoritos"
            : "♡ Adicionar aos favoritos";
        botaoFavorito.classList.toggle("favoritado", salvo);
    }

    atualizarBotao();

    botaoFavorito.addEventListener("click", () => {
        if (favoritos.includes(identificador)) {
            favoritos = favoritos.filter(id => id !== identificador);
        } else {
            favoritos.push(identificador);
        }

        localStorage.setItem("noirFavorites", JSON.stringify(favoritos));
        atualizarBotao();
    });
}
